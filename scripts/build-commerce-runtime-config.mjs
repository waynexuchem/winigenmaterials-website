import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(siteRoot, 'ecommerce/runtime-config.source.json');
const outputPath = resolve(siteRoot, 'assets/js/commerce-config.js');
const sessionRoutingOutputPath = resolve(siteRoot, 'assets/js/commerce-session-routing.js');
const mainScriptPath = resolve(siteRoot, 'assets/js/main.js');
const target = process.argv.find(value => value.startsWith('--target='))?.slice(9) || 'test';
const check = process.argv.includes('--check');
const contractOnly = process.argv.includes('--contract-only');
const allowedTargets = new Set(['test', 'production']);

if (!allowedTargets.has(target)) throw new Error('Use --target=test or --target=production.');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const environment = source.environments?.[target];
if (source.siteOrigin !== 'https://www.winigenmaterials.com') throw new Error('Commerce site origin is invalid.');
if (!environment?.apiOrigin?.startsWith('https://')) throw new Error(`Commerce API origin is missing for ${target}.`);
if (target === 'production' && environment.apiOrigin.includes('winigen-stripe-test')) {
  throw new Error('Production commerce configuration must not reference the sandbox Worker.');
}
if (target === 'test' && environment.apiOrigin !== 'https://winigen-stripe-test.winigen.workers.dev') {
  throw new Error('Test commerce configuration must reference the sandbox Worker.');
}

const output = `// Generated by scripts/build-commerce-runtime-config.mjs. Do not edit directly.
(function initializeCommerceConfig(global) {
  const hostname = global.location.hostname.toLowerCase();
  const isProduction = hostname === 'winigenmaterials.com' || hostname === 'www.winigenmaterials.com';
  const isLocal = hostname === 'localhost' || hostname === '127.0.0.1' || hostname === '[::1]';
  const config = isProduction
    ? { environment: 'production', siteOrigin: ${JSON.stringify(source.siteOrigin)}, apiOrigin: ${JSON.stringify(source.environments.production.apiOrigin)}, checkoutEnabled: true }
    : isLocal
      ? { environment: 'local', siteOrigin: global.location.origin, apiOrigin: ${JSON.stringify(source.environments.test.apiOrigin)}, checkoutEnabled: true }
      : { environment: 'preview', siteOrigin: global.location.origin, apiOrigin: null, checkoutEnabled: false, checkoutMessage: 'Checkout is disabled on this non-production preview.' };
  global.WINIGEN_COMMERCE_CONFIG = Object.freeze(config);
}(window));
`;
const sessionRoutingOutput = `// Generated by scripts/build-commerce-runtime-config.mjs. Do not edit directly.
(function (global) {
  const apiOrigins = Object.freeze(${JSON.stringify(Object.fromEntries(
    Object.entries(source.environments).map(([name, config]) => [name, config.apiOrigin])
  ), null, 2)});
  const smokeStateKey = 'winigen-live-smoke-test-attempt-v1';
  const sessionPatterns = Object.freeze({
    test: /^cs_test_[A-Za-z0-9]{20,255}$/,
    production: /^cs_live_[A-Za-z0-9]{20,255}$/
  });

  function resolveOrderStatusOrigin(sessionId) {
    if (sessionPatterns.test.test(sessionId || '')) return apiOrigins.test;
    if (sessionPatterns.production.test(sessionId || '')) return apiOrigins.production;
    return null;
  }

  function readSmokeState(storage = global.sessionStorage) {
    if (!storage) return null;
    try {
      const value = storage.getItem(smokeStateKey);
      if (!value) return null;
      const parsed = JSON.parse(value);
      return parsed && typeof parsed.attemptId === 'string' ? parsed : null;
    } catch {
      return null;
    }
  }

  function getOrCreateSmokeAttempt(createId, storage = global.sessionStorage) {
    const existing = readSmokeState(storage);
    if (existing?.attemptId) return existing.attemptId;
    const attemptId = createId();
    storage?.setItem(smokeStateKey, JSON.stringify({ attemptId, status: 'PENDING' }));
    return attemptId;
  }

  function recordSmokeCheckout({ attemptId, orderId }, storage = global.sessionStorage) {
    if (!storage || typeof attemptId !== 'string' || !attemptId || typeof orderId !== 'string' || !orderId) return false;
    storage.setItem(smokeStateKey, JSON.stringify({ attemptId, orderId, status: 'PENDING' }));
    return true;
  }

  function reconcilePaidSmokeCheckout({ orderId, paymentStatus }, storage = global.sessionStorage) {
    if (paymentStatus !== 'PAID' || !storage) return { reconciled: false, reason: 'NOT_PAID' };
    const state = readSmokeState(storage);
    if (!state?.orderId || state.orderId !== orderId) return { reconciled: false, reason: 'ORDER_MISMATCH' };
    storage.removeItem(smokeStateKey);
    return { reconciled: true, reason: 'PAID' };
  }

  global.WinigenCommerceRouting = Object.freeze({
    apiOrigins,
    resolveOrderStatusOrigin,
    readSmokeState,
    getOrCreateSmokeAttempt,
    recordSmokeCheckout,
    reconcilePaidSmokeCheckout
  });
}(typeof window === 'undefined' ? globalThis : window));
`;
const configVersion = createHash('sha256').update(output).digest('hex').slice(0, 12);
const mainScript = await readFile(mainScriptPath, 'utf8');
const synchronizedMainScript = mainScript.replace(
  /const commerceConfigVersion = '[^']+';/,
  `const commerceConfigVersion = '${configVersion}';`
);
if (synchronizedMainScript === mainScript && !mainScript.includes(`const commerceConfigVersion = '${configVersion}';`)) {
  throw new Error('assets/js/main.js is missing the commerce config-version declaration.');
}

if (contractOnly) {
  console.log(`Validated ${target} commerce runtime contract: ${environment.apiOrigin}`);
} else if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  const currentSessionRouting = await readFile(sessionRoutingOutputPath, 'utf8').catch(() => '');
  if (current !== output) throw new Error(`Generated commerce runtime config is stale for ${target}.`);
  if (currentSessionRouting !== sessionRoutingOutput) throw new Error('Generated commerce session routing is stale.');
  if (synchronizedMainScript !== mainScript) throw new Error(`assets/js/main.js has a stale commerce config fingerprint for ${target}.`);
  console.log(`Commerce runtime config matches ${target}.`);
} else {
  await writeFile(outputPath, output);
  await writeFile(sessionRoutingOutputPath, sessionRoutingOutput);
  if (synchronizedMainScript !== mainScript) await writeFile(mainScriptPath, synchronizedMainScript);
  console.log(`Generated ${outputPath} for ${target}.`);
}
